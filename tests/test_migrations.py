"""Backward compatibility with sessions written by Milestone 1 (schema 1.0.0).

``fixtures/session_schema_1_0_0.json`` was generated by the committed
Milestone 1 code (commit 23204e3), not hand-written.
"""

import json
import shutil
from pathlib import Path

import pytest
from pydantic import ValidationError

from hallucination_lab.migrations import migrate_session_data
from hallucination_lab.models import SCHEMA_VERSION, VerificationSession
from hallucination_lab.storage import JsonSessionStore

FIXTURE = Path(__file__).parent / "fixtures" / "session_schema_1_0_0.json"


@pytest.fixture
def v1_store(tmp_path):
    store = JsonSessionStore(tmp_path / "sessions")
    data = json.loads(FIXTURE.read_text())
    store.root.mkdir(parents=True)
    shutil.copy(FIXTURE, store.root / f"{data['session_id']}.json")
    return store, data


def test_fixture_really_is_schema_1_0_0():
    data = json.loads(FIXTURE.read_text())
    assert data["schema_version"] == "1.0.0"
    assert "retrieval_runs" not in data
    assert "passage_id" not in data["evidence"][0]


def test_v1_session_loads_with_content_intact(v1_store):
    store, data = v1_store
    session = store.load(data["session_id"])
    assert session.schema_version == SCHEMA_VERSION
    assert session.retrieval_runs == []
    assert session.response.text == data["response"]["text"]
    assert [c.claim_id for c in session.claims] == [c["claim_id"] for c in data["claims"]]
    assert session.evidence[0].quoted_passage == data["evidence"][0]["quoted_passage"]
    assert session.evidence[0].passage_sha256 is None  # not invented after the fact
    assert session.human_verdict(data["claims"][0]["claim_id"]).reviewer_id == "reviewer-1"


def test_resaving_v1_session_upgrades_version_only(v1_store):
    store, data = v1_store
    session = store.load(data["session_id"])
    path = store.save(session)
    saved = json.loads(path.read_text())
    assert saved["schema_version"] == SCHEMA_VERSION
    assert saved["claims"] == json.loads(json.dumps(data["claims"]))
    # Original fields are unchanged; newer optional fields appear only with empty defaults.
    for before, after in zip(data["verifications"], saved["verifications"], strict=True):
        assert {k: after[k] for k in before} == before
        assert after["session_id"] is None and after["evidence_assessments"] == []
        assert after["revision_of"] is None


def test_newer_minor_version_rejected_with_clear_message():
    data = json.loads(FIXTURE.read_text())
    data["schema_version"] = "1.9.0"
    with pytest.raises(ValidationError, match="newer version"):
        VerificationSession.model_validate(migrate_session_data(data))


def test_unknown_major_rejected():
    data = json.loads(FIXTURE.read_text())
    data["schema_version"] = "2.0.0"
    with pytest.raises(ValidationError, match="unsupported schema major"):
        VerificationSession.model_validate(migrate_session_data(data))


def test_migration_passes_through_unexpected_input():
    assert migrate_session_data([1, 2]) == [1, 2]
    assert migrate_session_data({"schema_version": "x"}) == {"schema_version": "x"}


FIXTURE_1_1 = Path(__file__).parent / "fixtures" / "session_schema_1_1_0.json"


def test_v1_1_session_loads_and_legacy_verdict_stays_active(tmp_path):
    """Fixture generated by the committed Milestone 2 code (commit 88176ed)."""
    data = json.loads(FIXTURE_1_1.read_text())
    assert data["schema_version"] == "1.1.0" and "verification_drafts" not in data
    store = JsonSessionStore(tmp_path / "sessions")
    store.root.mkdir(parents=True)
    shutil.copy(FIXTURE_1_1, store.root / f"{data['session_id']}.json")
    session = store.load(data["session_id"])
    legacy = session.verifications[0]
    assert session.schema_version == SCHEMA_VERSION
    assert legacy.session_id is None and legacy.evidence_assessments == []
    assert session.human_verdict(legacy.claim_id) == legacy
    assert len(session.retrieval_runs) == 1 and len(session.evidence) == 4
